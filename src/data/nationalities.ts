/** Strip accents + lowercase so "cote", "côte", "CINA" all compare sanely. */
export const normaliseSearch = (v: string): string =>
  v.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();

export const nationalityByCode = (code: string | null | undefined): NationalityEntry | undefined =>
  code ? NATIONALITY_ENTRIES.find((n) => n.code.toUpperCase() === code.toUpperCase()) : undefined;

/**
 * Resolve a stored value to an alpha-2 code. Accepts a code already, or legacy
 * free text such as "Chinese", "China", "United Kingdom".
 */
export const resolveNationalityCode = (value: string | null | undefined): string => {
  if (!value) return "";
  const raw = value.trim();
  if (!raw) return "";
  if (raw.length === 2 && nationalityByCode(raw)) return raw.toUpperCase();
  const q = normaliseSearch(raw);
  const hit =
    NATIONALITY_ENTRIES.find((n) => normaliseSearch(n.nationality) === q) ??
    NATIONALITY_ENTRIES.find((n) => normaliseSearch(n.country) === q) ??
    NATIONALITY_ENTRIES.find((n) => normaliseSearch(n.country).includes(q) || normaliseSearch(n.nationality).includes(q));
  return hit?.code ?? "";
};

export const matchesNationalityQuery = (n: NationalityEntry, query: string): boolean => {
  const q = normaliseSearch(query);
  if (!q) return true;
  return (
    normaliseSearch(n.nationality).includes(q) ||
    normaliseSearch(n.country).includes(q) ||
    n.code.toLowerCase() === q
  );
};
